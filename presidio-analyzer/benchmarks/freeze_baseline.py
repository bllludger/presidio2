"""Freeze local runtime inputs; verify integrity before reproducibility scans.

Snapshots contain local corpus inputs: keep them outside version control.
This does not install packages, change rules, or claim end-to-end chat capacity.
"""

import argparse
import hashlib
import importlib.metadata as metadata
import json
import os
import platform
import shutil
import subprocess
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

SOURCES = {
    "pii": "datasets/pii/ru-banking-privacy/critical-250.jsonl",
    "secrets": "datasets/secrets/creddetx/critical-250.jsonl",
    "negatives": "datasets/false-positives/curated-hard-negatives-500/cases.jsonl",
    "server": "load-testing/runs/campaign-remaining-20261120/cases-diverse.jsonl",
}
ROOTS = ("core", "installed", "port", "corpora", "harness")
# Keep dependency discovery stable when frozen source paths are prepended later.
PACKAGE_SEARCH_PATH = tuple(sys.path)
ENV_KEYS = (
    "REGEX_TIMEOUT_SECONDS",
    "OMP_NUM_THREADS",
    "OPENBLAS_NUM_THREADS",
    "MKL_NUM_THREADS",
    "PYTHONHASHSEED",
)


def digest(data):
    """Return a content fingerprint."""
    return hashlib.sha256(data).hexdigest()


def file_inventory(root):
    """Hash relative paths as well as contents; ignore generated bytecode only."""
    return {
        p.relative_to(root).as_posix(): digest(p.read_bytes())
        for p in sorted(Path(root).rglob("*"))
        if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"
    }


def runtime():
    """Fingerprint installed package code/data, not only version labels."""
    packages = {}
    for dist in metadata.distributions(path=PACKAGE_SEARCH_PATH):
        files = {}
        for relative in dist.files or ():
            if str(relative).endswith(".pyc") or "__pycache__" in str(relative):
                continue
            path = dist.locate_file(relative)
            if path.is_file():
                files[str(relative)] = digest(path.read_bytes())
        packages[dist.metadata["Name"].lower()] = {
            "version": dist.version,
            "files_sha256": digest(json.dumps(files, sort_keys=True).encode()),
            "file_count": len(files),
        }
    executable = Path(sys.executable).resolve()
    return {
        "python": sys.version,
        "executable": str(executable),
        "executable_sha256": digest(executable.read_bytes()),
        "platform": platform.platform(),
        "packages": packages,
        "environment": {key: os.environ.get(key) for key in ENV_KEYS},
    }


def verify(snapshot, check_runtime=True):
    """Reject missing, modified or added inputs, including changed harness code."""
    manifest = json.loads((snapshot / "manifest.json").read_text())
    for name in ROOTS:
        if file_inventory(snapshot / name) != manifest["files"][name]:
            raise ValueError(f"baseline input drift: {name}")
    if check_runtime and runtime() != manifest["runtime"]:
        raise ValueError("baseline runtime drift")
    return manifest


def copy_tree(source, target):
    """Copy runtime inputs without generated bytecode."""
    shutil.copytree(
        source,
        target,
        ignore=shutil.ignore_patterns("__pycache__", "*.pyc", ".DS_Store"),
    )


def capture(args):
    """Copy working source, installed analyzer, profile and exact corpus files."""
    root, target = args.workspace.resolve(), args.snapshot.resolve()
    target.mkdir(parents=True, exist_ok=False, mode=0o700)
    (target / ".gitignore").write_text("*\n")
    core = root / "presidio-ru-core/presidio-analyzer"
    port = root / "litellm-presidio-port"
    # Distribution location is deliberately independent of PYTHONPATH/source imports.
    installed = Path(
        metadata.distribution("presidio-analyzer").locate_file("presidio_analyzer")
    )
    copy_tree(core / "presidio_analyzer", target / "core/presidio_analyzer")
    copy_tree(installed, target / "installed/presidio_analyzer")
    copy_tree(port / "profile", target / "port/profile")
    copy_tree(port / "src", target / "port/src")
    (target / "port/config").mkdir()
    shutil.copy2(port / "config/litellm.yaml", target / "port/config/litellm.yaml")
    (target / "harness").mkdir()
    shutil.copy2(__file__, target / "harness/freeze_baseline.py")
    shutil.copy2(
        Path(__file__).with_name("evaluate_ru_port.py"),
        target / "harness/evaluate_ru_port.py",
    )
    shutil.copy2(
        port / "tests/openrouter_history.py", target / "harness/openrouter_history.py"
    )
    for name in ("pyproject.toml", "uv.lock"):
        shutil.copy2(core / name, target / "core" / name)
    (target / "corpora").mkdir()
    for name, relative in SOURCES.items():
        shutil.copy2(root / relative, target / "corpora" / f"{name}.jsonl")
    before = runtime()
    manifest = {
        "schema": 1,
        "captured_utc": datetime.now(timezone.utc).isoformat(),
        "scope": "Frozen direct Detector + local span cache; no running service",
        "runtime": before,
        "logical_cpus": os.cpu_count(),
        "heads": {
            name: subprocess.check_output(
                ["git", "-C", str(root / name), "rev-parse", "HEAD"], text=True
            ).strip()
            for name in ("presidio-ru-core", "litellm-presidio-port")
        },
        "files": {name: file_inventory(target / name) for name in ROOTS},
        "corpus_origin": SOURCES,
        "notes": [
            "Working-tree bytes, not HEAD, define this baseline.",
            "Installed and source variants are separate baselines.",
            "Same-machine replay requires the captured interpreter and packages.",
            "No secrets/environment values outside the explicit ENV_KEYS are captured.",
        ],
    }
    # A concurrent edit during capture must not silently produce a mixed snapshot.
    for origin, frozen in [
        (core / "presidio_analyzer", target / "core/presidio_analyzer"),
        (installed, target / "installed/presidio_analyzer"),
        (port / "profile", target / "port/profile"),
        (port / "src", target / "port/src"),
    ]:
        if file_inventory(origin) != file_inventory(frozen):
            raise ValueError("source changed during baseline capture")
    for origin, frozen in (
        [
            (root / relative, target / "corpora" / f"{name}.jsonl")
            for name, relative in SOURCES.items()
        ]
        + [
            (port / "config/litellm.yaml", target / "port/config/litellm.yaml"),
            (
                port / "tests/openrouter_history.py",
                target / "harness/openrouter_history.py",
            ),
        ]
        + [
            (Path(__file__).with_name(name), target / "harness" / name)
            for name in ("freeze_baseline.py", "evaluate_ru_port.py")
        ]
        + [
            (core / name, target / "core" / name)
            for name in ("pyproject.toml", "uv.lock")
        ]
    ):
        if origin.read_bytes() != frozen.read_bytes():
            raise ValueError("file changed during baseline capture")
    (target / "manifest.json").write_text(
        json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    )
    print(
        json.dumps(
            {
                "snapshot": str(target),
                "manifest_sha256": digest((target / "manifest.json").read_bytes()),
            }
        )
    )


def read_corpus(path):
    """Validate schema, unique IDs and annotated Unicode character offsets."""
    rows, ids = [], set()
    for line in path.read_text().splitlines():
        row = json.loads(line)
        key = row.get("case_id", row.get("id"))
        text = row.get("input", row.get("text"))
        if key is None or key in ids or not isinstance(text, str):
            raise ValueError("invalid or duplicate corpus record")
        ids.add(key)
        for label in row.get("entities", []) + row.get("negatives", []):
            a, b = label["start"], label["end"]
            if not (type(a) is type(b) is int and 0 <= a < b <= len(text)):
                raise ValueError("invalid label offsets")
            if "value" in label and text[a:b] != label["value"]:
                raise ValueError("invalid label value")
        rows.append(row)
    if not rows:
        raise ValueError("empty corpus")
    return rows


def check_reference(expected, variant, manifest_sha256, signature):
    """Compare outputs only for the exact same baseline and variant."""
    if expected["variant"] != variant or expected["manifest_sha256"] != manifest_sha256:
        raise ValueError("incompatible baseline reference")
    if expected["outputs_sha256"] != signature:
        raise AssertionError("baseline outputs changed")


def run(args):
    """Measure a frozen variant and enforce exact outputs on replay."""
    snapshot = args.snapshot.resolve()
    manifest = verify(snapshot)
    manifest_sha256 = digest((snapshot / "manifest.json").read_bytes())
    if Path(__file__).resolve() != snapshot / "harness/freeze_baseline.py":
        raise ValueError("execute the frozen harness inside the snapshot")
    output = args.output.resolve()
    if output == snapshot / "manifest.json" or any(
        snapshot / name in output.parents for name in ROOTS
    ):
        raise ValueError("output would overwrite frozen inputs")
    sys.path[:0] = [
        str(snapshot / args.variant),
        str(snapshot / "port/profile/src"),
        str(snapshot / "port/src"),
        str(snapshot / "harness"),
    ]
    import presidio_analyzer
    from detector import Detector
    from evaluate_ru_port import quality
    from openrouter_history import messages_for
    from presidio_ru_litellm.analyzer import CachedTextDetector

    if (
        snapshot / args.variant
        not in Path(presidio_analyzer.__file__).resolve().parents
    ):
        raise ValueError("wrong analyzer imported")
    start = time.perf_counter()

    class CountingDetector:
        """Observe actual cache misses without changing detector behavior."""

        def __init__(self):
            self.inner = Detector()
            self.max_text_length = self.inner.max_text_length
            self.calls = 0

        def detect(self, payload):
            self.calls += 1
            return self.inner.detect(payload)

    detector = CountingDetector()
    initialization = time.perf_counter() - start
    rows = []
    labeled, predictions = [], []
    corpora = {
        name: read_corpus(snapshot / "corpora" / f"{name}.jsonl") for name in SOURCES
    }

    def measure(group, key, texts, scan):
        calls_before = detector.calls
        started, cpu = time.perf_counter_ns(), time.process_time_ns()
        spans = [scan(text) for text in texts]
        cpu_ms = (time.process_time_ns() - cpu) / 1e6
        wall_ms = (time.perf_counter_ns() - started) / 1e6
        for text, findings in zip(texts, spans):
            previous = 0
            for left, right in findings:
                if not (
                    type(left) is type(right) is int
                    and previous <= left < right <= len(text)
                ):
                    raise AssertionError("invalid masking offsets")
                previous = right
        rows.append(
            {
                "group": group,
                "id": key,
                "blocks": len(texts),
                "utf8_bytes": sum(len(t.encode()) for t in texts),
                "input_sha256": digest(json.dumps(texts, ensure_ascii=False).encode()),
                "detector_calls": detector.calls - calls_before,
                "spans": spans,
                "cpu_ms": cpu_ms,
                "wall_ms": wall_ms,
            }
        )

    def direct(text):
        return detector.detect({"text": text})

    # First traversal is explicitly first-use, not a claim of OS/model coldness.
    for repeat in range(2):
        for name in SOURCES:
            for index, row in enumerate(corpora[name]):
                text = row.get("input", row.get("text"))
                group = f"{name}-pass{repeat + 1}"
                if name == "server":
                    size = 8 if len(text.encode()) < 16000 else 32
                    group = f"server-{size}KB-pass{repeat + 1}"
                measure(group, index, [text], direct)
                if repeat == 0 and name != "server":
                    labeled.append(("negative" if name == "negatives" else name, row))
                    predictions.append((index, rows[-1]["spans"][0]))
    # Fixed arrival order; no sleeps or offered RPS claims in a CPU baseline.
    cached = CachedTextDetector(detector)
    history = [m["content"] for m in messages_for("baseline-fixed", "code")[:4]]
    for text in history:
        cached.scan(text)
    for i in range(12):
        fresh = [m["content"] for m in messages_for(f"baseline-new-{i:04d}", "code")]
        measure("new-chat", i, fresh, direct)
        measure("history-chat", i, history + [fresh[-1]], cached.scan)
        mixed_fresh = [
            m["content"] for m in messages_for(f"baseline-mixed-{i:04d}", "code")
        ]
        mixed = mixed_fresh if i % 2 else history + [mixed_fresh[-1]]
        measure("mixed-chat", i, mixed, cached.scan)
        if [row["detector_calls"] for row in rows[-3:]] != [5, 1, 5 if i % 2 else 1]:
            raise AssertionError("chat workload cache behavior changed")
    correctness = [
        {k: v for k, v in row.items() if k not in ("cpu_ms", "wall_ms")} for row in rows
    ]
    signature = digest(json.dumps(correctness, sort_keys=True).encode())
    if args.expect:
        expected = json.loads(args.expect.read_text())
        check_reference(expected, args.variant, manifest_sha256, signature)
    # Verify inputs again: an edit during measurement invalidates the run.
    if verify(snapshot) != manifest:
        raise ValueError("baseline manifest changed during run")
    result = {
        "variant": args.variant,
        "analyzer_file": presidio_analyzer.__file__,
        "manifest_sha256": manifest_sha256,
        "executed_utc": datetime.now(timezone.utc).isoformat(),
        "command": sys.argv,
        "workers": 1,
        "passes": 2,
        "quality": quality(labeled, predictions),
        "outputs_sha256": signature,
        "initialization_seconds": initialization,
        "scope": (
            "Direct analysis; first-use and repeat passes; internal caches "
            "remain enabled. Chat history uses worker-local span cache only."
        ),
        "rows": rows,
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n")
    print(
        json.dumps(
            {
                "variant": args.variant,
                "records": len(rows),
                "outputs_sha256": signature,
                "replay_matches": bool(args.expect),
            }
        )
    )


def main():
    """Capture inputs or replay a frozen baseline."""
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    capture_parser = sub.add_parser("capture")
    capture_parser.add_argument("--workspace", type=Path, required=True)
    capture_parser.add_argument("--snapshot", type=Path, required=True)
    run_parser = sub.add_parser("run")
    run_parser.add_argument("--snapshot", type=Path, required=True)
    run_parser.add_argument("--variant", choices=["core", "installed"], required=True)
    run_parser.add_argument("--output", type=Path, required=True)
    run_parser.add_argument("--expect", type=Path)
    args = parser.parse_args()
    capture(args) if args.command == "capture" else run(args)


if __name__ == "__main__":
    main()
